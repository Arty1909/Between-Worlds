function arrivalFor(previous,next){
  if(!previous?.started||!next?.started||next.kind==='ending'||previous.node===next.node||previous.bg===next.bg)return null;
  const copy=WORLD_ARRIVALS[next.bg];
  return copy?{title:copy[0],text:copy[1]}:null;
}
window.arrivalFor=arrivalFor;
